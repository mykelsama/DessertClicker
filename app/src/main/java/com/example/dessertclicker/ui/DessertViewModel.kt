package com.example.dessertclicker.ui

import androidx.lifecycle.ViewModel
import com.example.dessertclicker.data.Datasource.dessertList
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update

class DessertViewModel : ViewModel() {

    private val _uiState = MutableStateFlow(DessertUiState())
    val uiState: StateFlow<DessertUiState> = _uiState.asStateFlow()

    fun onDessertClicked() {
        _uiState.update { cs ->
            val dessertsSold = cs.dessertsSold + 1
            val nextIndex = determineDessertIndex(dessertsSold)
            cs.copy(
                revenue = cs.revenue + cs.currentDessertPrice,
                dessertsSold = dessertsSold,
                currentDessertIndex = nextIndex,
                currentDessertImageId = dessertList[nextIndex].imageId,
                currentDessertPrice = dessertList[nextIndex].price
            )
        }
    }

    private fun determineDessertIndex(dessertsSold: Int): Int {
        var dessertIndex = 0
        for (index in dessertList.indices) {
            if (dessertsSold >= dessertList[index].startProductionAmount) {
                dessertIndex = index
            } else {
                break
            }
        }
        return dessertIndex
    }
}